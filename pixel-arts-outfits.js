// pixel-arts-outfits.js
// Real art for the unlockable "おめかし" (outfit/accessory) and "えさ" (food)
// rewards, kept in its own file (separate from pixel-arts.js and
// pixel-arts-legendary.js) so it can keep evolving without touching the
// default-cat registry or the app logic in app.js.
//
// Each item is a single static 16x16 icon (unlike the cats in pixel-arts.js,
// which have multiple named poses) -- OUTFIT_ART[key] / FOOD_ART[key] each
// have a `name`, a `colors` palette map, and a 16x16 `grid`.
//
// おめかし items also carry an `overlay` hint used by app.js's
// compositeOutfitOverlay() (called from both renderCatWithOutfit() for the
// walking/sitting cat, and renderStretchProgressBar() for the のびるねこ
// head piece) to composite the equipped item directly onto the base sprite
// (see that function for exactly how scale/anchor/offset are applied):
//   - { scale: 1, anchor: 'full' } -- drawn at the base sprite's own scale,
//     in the exact same position as its 16x16 grid (used for 首輪, which was
//     drawn to already line up with the cat's neck at 1:1).
//   - { scale: 0.7, anchor: 'top-right' } -- drawn at 70% of the base
//     sprite's size, anchored to the top-right corner of its bounding box,
//     which lands it roughly on top of the head (used for リボン／王冠).
//   - optional `offsetX`/`offsetY` (px) -- a fixed nudge on top of the
//     anchor position for fine-tuning (positive X = right, positive Y =
//     down), set from direct visual feedback rather than derived from the
//     art. Used as the fallback whenever a pose-specific value below isn't
//     given for the pose actually being rendered.
//   - optional `byPose: { sitting: {offsetX,offsetY}, walking: {...} }` --
//     since 座ってる/歩いてる姿勢でズレ方が違うアイテム（首輪・王冠）向けの
//     姿勢別の上書き値。片方の姿勢しか書かなければ、もう片方は上の
//     offsetX/offsetY（未指定なら0,0）にフォールバックする。
//     compositeOutfitOverlay(baseHtml, cols, rows, cellPx, pose) の pose引数
//     で解決される（app.jsのrenderCatWithOutfit()/renderStretchProgressBar()
//     が実際のsitting/walkingを渡す）。
//     2026-08-24の位置調整（猫のピクセル1マス=3pxとして換算）:
//       リボン: offsetY -3 → -5（5px上げ。座り／歩き共通のまま）
//       首輪: sitting {offsetX:-3, offsetY:0}（3px左）／
//             walking {offsetX:0, offsetY:-3}（3px上、横は動かさない）
//       王冠: offsetX 3 → -2（5px左へ）は座り姿勢のデフォルトとして維持、
//             walkingはそこからさらに3px上げて offsetY -10 → -13。
//     2026-08-24 追加の位置調整（同日2回目。上の値からさらに調整）:
//       首輪: sitting offsetX -3 → 0（3px右へ）／
//             walking offsetY -3 → -8（5px上へ）
//       リボン: sitting offsetY -5 → 0（5px下げ）／
//              walking offsetY -5 → -8（3px上げ）
//              （座り／歩きでズレ方が違うようになったため、リボンも
//              首輪・王冠と同じくbyPoseで座り/歩きを分けるように変更）
//       王冠: 座り姿勢は変更なし（offsetX -2, offsetY -10のまま）／
//             walkingはoffsetX -2→1（3px右へ）、offsetY -13→-16（3px上へ）
//     2026-08-24 3回目の調整（ユーザーによる自己修正を引き継ぎ、破損を修正）:
//       首輪: walking offsetY -8 → -6（2px下げ）。sitting は変更なし
//             （0,0のまま。自己修正時にoffsetXが-1に変わっていたが、
//             「座ってるときOK」の指示どおり0に戻した）。
//       リボン: sitting offsetXを-2に（2px左へ）。自己修正時は符号が逆の
//              +2になっており、実際には右に動いてしまっていたので修正。
//              walkingは変更なし（offsetY -8のまま、指示どおりOK）。
//       王冠: 位置(overlay)は変更なし。ただしgridデータに構文エラーが
//             あった（1行目の配列リテラルの後にカンマが無く、直後の配列が
//             インデックスアクセス式として解釈されてしまい、行が1つ欠落
//             ＋先頭に余計な空白行が1つ増えていた）。JS的にはこれでも
//             パースは通ってしまう（構文エラーにならない）ため、実行時に
//             art.grid[0].mapが存在せずrender()全体が例外で止まり、
//             アプリ全体が真っ白になっていた（「何も出てこなくなった」の
//             原因）。デザインを縮小したものに差し替えたとのことだったが、
//             届いたデータは上記の破損を除けば元の王冠と同一だったため、
//             ひとまず元の16行の王冠グリッドに復元した。本当に縮小した
//             デザインに差し替えたい場合は、新しいgridデータを送ってください。
//
// Loaded via <script> before app.js (and after pixel-arts.js), so these
// become globals: OUTFIT_ART, FOOD_ART.

